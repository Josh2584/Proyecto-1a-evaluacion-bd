-- Usuarios (pueden comentar y publicar).
CREATE TABLE Blog_Users (
    User_Id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Full_Name     VARCHAR2(100) NOT NULL,
    Email         VARCHAR2(254) NOT NULL,
    Created_At    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_blog_users_email UNIQUE (Email),
    CONSTRAINT ck_blog_users_email CHECK (INSTR(Email, '@') > 1)
);

-- Temas generales.
CREATE TABLE Blog_Categories (
    Category_Id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name          VARCHAR2(80) NOT NULL,
    Slug          VARCHAR2(80) NOT NULL,
    CONSTRAINT uq_blog_categories_name UNIQUE (Name),
    CONSTRAINT uq_blog_categories_slug UNIQUE (Slug),
    CONSTRAINT ck_blog_categories_slug CHECK (REGEXP_LIKE(Slug, '^[a-z0-9]+(-[a-z0-9]+)*$'))
);

-- Descripción del artículo más detallada.
CREATE TABLE Blog_Tags (
    Tag_Id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name          VARCHAR2(60) NOT NULL,
    Slug          VARCHAR2(60) NOT NULL,
    CONSTRAINT uq_blog_tags_name UNIQUE (Name),
    CONSTRAINT uq_blog_tags_slug UNIQUE (Slug),
    CONSTRAINT ck_blog_tags_slug CHECK (REGEXP_LIKE(Slug, '^[a-z0-9]+(-[a-z0-9]+)*$'))
);

-- Contenido principal del blog.
CREATE TABLE Blog_Articles (
    Article_Id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Author_Id     NUMBER NOT NULL,
    Title         VARCHAR2(180) NOT NULL,
    Body          CLOB NOT NULL,
    Published_At  TIMESTAMP,
    Created_At    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    Updated_At    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_blog_articles_author FOREIGN KEY (Author_Id)
        REFERENCES Blog_Users(User_Id)
);

-- Un artículo puede tener varias etiquetas.
CREATE TABLE Blog_Article_Tags (
    Article_Id    NUMBER NOT NULL,
    Tag_Id        NUMBER NOT NULL,
    CONSTRAINT pk_blog_article_tags PRIMARY KEY (Article_Id, Tag_Id),
    CONSTRAINT fk_bat_article FOREIGN KEY (Article_Id)
        REFERENCES Blog_Articles(Article_Id) ON DELETE CASCADE,
    CONSTRAINT fk_bat_tag FOREIGN KEY (Tag_Id)
        REFERENCES Blog_Tags(Tag_Id) ON DELETE CASCADE
);

-- Un artículo puede estar en una o varias categorías.
CREATE TABLE Blog_Article_Categories (
    Article_Id    NUMBER NOT NULL,
    Category_Id   NUMBER NOT NULL,
    CONSTRAINT pk_blog_article_categories PRIMARY KEY (Article_Id, Category_Id),
    CONSTRAINT fk_bac_article FOREIGN KEY (Article_Id)
        REFERENCES Blog_Articles(Article_Id) ON DELETE CASCADE,
    CONSTRAINT fk_bac_category FOREIGN KEY (Category_Id)
        REFERENCES Blog_Categories(Category_Id) ON DELETE CASCADE
);

-- Opiniones de los usuarios.
CREATE TABLE Blog_Comments (
    Comment_Id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Article_Id    NUMBER NOT NULL,
    User_Id       NUMBER NOT NULL,
    Body          VARCHAR2(1000) NOT NULL,
    Created_At    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_blog_comments_article FOREIGN KEY (Article_Id)
        REFERENCES Blog_Articles(Article_Id) ON DELETE CASCADE,
    CONSTRAINT fk_blog_comments_user FOREIGN KEY (User_Id)
        REFERENCES Blog_Users(User_Id),
    CONSTRAINT ck_blog_comments_body CHECK (LENGTH(TRIM(Body)) >= 3)
);

CREATE INDEX ix_blog_articles_author ON Blog_Articles(Author_Id);
CREATE INDEX ix_blog_comments_article ON Blog_Comments(Article_Id);

