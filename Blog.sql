-- Explicación de cómo se realiza cada acción anterior.
CREATE OR REPLACE PACKAGE Body Blog_Pkg AS
    PROCEDURE require_rows(p_rows IN NUMBER, p_message IN VARCHAR2) IS
    BEGIN
        -- Evita informar éxito cuando no existe el registro indicado.
        IF p_rows = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, p_message);
        END IF;
    END;

    PROCEDURE create_user(p_name IN VARCHAR2, p_email IN VARCHAR2, p_id OUT NUMBER) IS
    BEGIN
        INSERT INTO Blog_Users(Full_Name, Email) VALUES (TRIM(p_name), LOWER(TRIM(p_email)))
        RETURNING User_Id INTO p_id;
    END;
    PROCEDURE update_user(p_id IN NUMBER, p_name IN VARCHAR2, p_email IN VARCHAR2) IS
    BEGIN
        UPDATE Blog_Users SET Full_Name=TRIM(p_name), Email=LOWER(TRIM(p_email) ) WHERE User_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'El usuario no existe.');
    END;
    PROCEDURE delete_user(p_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Users WHERE User_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'El usuario no existe o tiene registros relacionados.');
    END;

    PROCEDURE create_category(p_name IN VARCHAR2, p_slug IN VARCHAR2, p_id OUT NUMBER) IS
    BEGIN
        INSERT INTO Blog_Categories(Name, Slug) VALUES (TRIM(p_name), LOWER(TRIM(p_slug))) RETURNING Category_Id INTO p_id;
    END;
    PROCEDURE update_category(p_id IN NUMBER, p_name IN VARCHAR2, p_slug IN VARCHAR2) IS
    BEGIN
        UPDATE Blog_Categories SET Name=TRIM(p_name), Slug=LOWER(TRIM(p_slug)) WHERE Category_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'La categoria no existe.');
    END;
    PROCEDURE delete_category(p_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Categories WHERE Category_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'La categoria no existe o esta en uso.');
    END;

    PROCEDURE create_tag(p_name IN VARCHAR2, p_slug IN VARCHAR2, p_id OUT NUMBER) IS
    BEGIN
        INSERT INTO Blog_Tags(Name, Slug) VALUES (TRIM(p_name), LOWER(TRIM(p_slug))) RETURNING Tag_Id INTO p_id;
    END;
    PROCEDURE update_tag(p_id IN NUMBER, p_name IN VARCHAR2, p_slug IN VARCHAR2) IS
    BEGIN
        UPDATE Blog_Tags SET Name=TRIM(p_name), Slug=LOWER(TRIM(p_slug)) WHERE Tag_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'La etiqueta no existe.');
    END;
    PROCEDURE delete_tag(p_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Tags WHERE Tag_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'La etiqueta no existe o esta asignada.');
    END;

    PROCEDURE create_article(p_author_id IN NUMBER, p_title IN VARCHAR2, p_body IN CLOB, p_publish IN NUMBER, p_id OUT NUMBER) IS
    BEGIN
        INSERT INTO Blog_Articles(Author_Id, Title, Body, Published_At)
        VALUES (p_author_id, TRIM(p_title), p_body,
                CASE WHEN p_publish=1 THEN SYSTIMESTAMP ELSE NULL END)
        RETURNING Article_Id INTO p_id;
    END;
    PROCEDURE update_article(p_id IN NUMBER, p_author_id IN NUMBER, p_title IN VARCHAR2, p_body IN CLOB, p_publish IN NUMBER) IS
    BEGIN
        UPDATE Blog_Articles SET Author_Id=p_author_id, Title=TRIM(p_title),
            Body=p_body, Published_At=CASE WHEN p_publish=1 THEN NVL(Published_At,SYSTIMESTAMP) ELSE NULL END,
            Updated_At=SYSTIMESTAMP WHERE Article_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'El articulo no existe.');
    END;
    PROCEDURE delete_article(p_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Articles WHERE Article_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'El articulo no existe.');
    END;
    PROCEDURE assign_tag(p_article_id IN NUMBER, p_tag_id IN NUMBER) IS
    BEGIN
        INSERT INTO Blog_Article_Tags(Article_Id,Tag_Id) VALUES(p_article_id,p_tag_id);
    END;
    PROCEDURE unassign_tag(p_article_id IN NUMBER, p_tag_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Article_Tags WHERE Article_Id=p_article_id AND Tag_Id=p_tag_id;
        require_rows(SQL%ROWCOUNT, 'La asignacion no existe.');
    END;
    PROCEDURE clear_tags(p_article_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Article_Tags WHERE Article_Id=p_article_id;
    END;
    PROCEDURE assign_category(p_article_id IN NUMBER, p_category_id IN NUMBER) IS
    BEGIN
        INSERT INTO Blog_Article_Categories(Article_Id,Category_Id) VALUES(p_article_id,p_category_id);
    END;
    PROCEDURE clear_categories(p_article_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Article_Categories WHERE Article_Id=p_article_id;
    END;

    PROCEDURE create_comment(p_article_id IN NUMBER, p_user_id IN NUMBER, p_body IN VARCHAR2, p_id OUT NUMBER) IS
    BEGIN
        INSERT INTO Blog_Comments(Article_Id,User_Id,Body) VALUES(p_article_id,p_user_id,TRIM(p_body)) RETURNING Comment_Id INTO p_id;
    END;
    PROCEDURE update_comment(p_id IN NUMBER, p_body IN VARCHAR2) IS
    BEGIN
        UPDATE Blog_Comments SET Body=TRIM(p_body) WHERE Comment_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'El comentario no existe.');
    END;
    PROCEDURE delete_comment(p_id IN NUMBER) IS
    BEGIN
        DELETE FROM Blog_Comments WHERE Comment_Id=p_id;
        require_rows(SQL%ROWCOUNT, 'El comentario no existe.');
    END;
    FUNCTION article_count RETURN NUMBER IS v_total NUMBER; BEGIN SELECT COUNT(*) INTO v_total FROM Blog_Articles; RETURN v_total; END;
    FUNCTION comment_count RETURN NUMBER IS v_total NUMBER; BEGIN SELECT COUNT(*) INTO v_total FROM Blog_Comments; RETURN v_total; END;
END Blog_Pkg;
